/**
 * Generate the emoji tables from GitHub's gemoji database (MIT), which
 * follows the Unicode emoji list and carries the :shortcodes: most chat
 * tools agree on.
 *
 *   node scripts/build-emoji.mjs [path/to/emoji.json]
 *
 * Writes two files, both committed so builds need no network:
 *
 *   src/shared/emoji-codes.js  every shortcode, and which of them take a
 *                              skin tone; the worker validates reaction keys
 *                              against this, so nothing arbitrary can become
 *                              a storage path
 *   src/lib/emoji-data.js      the full table for the client: character,
 *                              shortcodes, category, keywords; loaded on
 *                              demand by src/lib/emoji.js
 */
import { readFileSync, writeFileSync } from 'node:fs';

const SOURCE = 'https://raw.githubusercontent.com/github/gemoji/master/db/emoji.json';
const KEY_RE = /^[a-z0-9_+-]{1,40}$/;

async function load(path) {
  if (path) return JSON.parse(readFileSync(path, 'utf8'));
  const res = await fetch(SOURCE);
  if (!res.ok) throw new Error(`fetch failed: ${res.status}`);
  return res.json();
}

const raw = await load(process.argv[2]);
const categories = [];
const rows = [];
const codes = new Set();
const toned = new Set();
for (const e of raw) {
  const aliases = (e.aliases || []).map((a) => a.toLowerCase()).filter((a) => KEY_RE.test(a) && !codes.has(a));
  if (!aliases.length) continue;
  let cat = categories.indexOf(e.category);
  if (cat === -1) cat = categories.push(e.category) - 1;
  for (const a of aliases) {
    codes.add(a);
    if (e.skin_tones) toned.add(a);
  }
  const tags = [...new Set((e.tags || []).concat(e.description.split(/\s+/)))]
    .map((t) => t.toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim()).filter(Boolean);
  rows.push([e.emoji, aliases.join(' '), cat, tags.join(' '), e.skin_tones ? 1 : 0]);
}

const header = (what) => `/* Generated by scripts/build-emoji.mjs from ${SOURCE}; do not edit. ${what} */\n`;

writeFileSync('src/shared/emoji-codes.js', header('Shortcodes only, shared with the worker.')
  + `const CODES = ${JSON.stringify([...codes].join(' '))};\n`
  + `const TONED = ${JSON.stringify([...toned].join(' '))};\n`
  + '/** Every known :shortcode:. */\nexport const EMOJI_CODES = new Set(CODES.split(\' \'));\n'
  + '/** Shortcodes whose emoji takes a skin tone modifier. */\nexport const EMOJI_TONED = new Set(TONED.split(\' \'));\n');

writeFileSync('src/lib/emoji-data.js', header('Full table for the client.')
  + `export const CATEGORIES = ${JSON.stringify(categories)};\n`
  + '/** [emoji, "alias alias", categoryIndex, "keywords", skinTones] */\n'
  + `export default ${JSON.stringify(rows)};\n`);

console.log(`${rows.length} emoji, ${codes.size} shortcodes (${toned.size} with skin tones), ${categories.length} categories`);
