"""Rebuild packaged webfonts from the hash-pinned official static downloads.

Usage: python scripts/build-font-resources.py /path/to/download-cache
Requires fonttools[woff]==4.65.0 and brotli==1.2.0 (build tools only).
The cache is populated from SOURCES.json; no glyphs or shaping tables are removed.
"""

import hashlib
import json
from pathlib import Path
import sys
import urllib.request

from fontTools.ttLib import TTFont
from fontTools.ttLib.woff2 import WOFF2FlavorData

root = Path(__file__).resolve().parent.parent
destination = root / "src/assets/fonts"
cache = Path(sys.argv[1])
cache.mkdir(parents=True, exist_ok=True)
manifest = json.loads((destination / "SOURCES.json").read_text())
families = {}

for record in manifest:
    source = cache / record["file"]
    if not source.exists():
        source.write_bytes(urllib.request.urlopen(record["url"]).read())
    assert hashlib.sha256(source.read_bytes()).hexdigest() == record["sha256"]
    font = TTFont(source, recalcTimestamp=False, recalcBBoxes=False)
    font.flavor = "woff2"
    # Compression only: disable WOFF2 glyph/metric transforms as well.
    font.flavorData = WOFF2FlavorData(transformedTables=set())
    output = destination / record["output"]
    font.save(output, reorderTables=False)
    original, result = TTFont(source), TTFont(output)
    assert set(original.reader.keys()) == set(result.reader.keys())
    for tag in original.reader.keys():
        before, after = original.reader[tag], result.reader[tag]
        if tag == "head":
            # WOFF2 sets flags bit11 (lossless compression) and recalculates
            # checkSumAdjustment. Every other header byte must be unchanged.
            expected = bytearray(before)
            expected[8:12] = after[8:12]
            expected[16] |= 8
            assert bytes(expected) == after
        else:
            assert before == after, (source.name, tag)
    record.update(
        outputSha256=hashlib.sha256(output.read_bytes()).hexdigest(),
        bytes=output.stat().st_size,
        conversion="fontTools 4.65.0 / Brotli 1.2.0 WOFF2 compression without "
        "table transforms; all table bytes verified unchanged except WOFF2 "
        "head compression flag and checksum",
    )
    families.setdefault(record["family"], []).append(
        dict(
            style=record["style"],
            weight=record["weight"],
            url=record["output"],
            variable="fvar" in result,
            legacyKerning="kern" in result,
        )
    )

catalog = [dict(family=family, faces=faces) for family, faces in families.items()]
js = json.dumps(catalog, indent=2)
for record in manifest:
    filename = record["output"]
    js = js.replace(
        '"url": ' + json.dumps(filename),
        '"url": new URL(' + json.dumps("./assets/fonts/" + filename)
        + ", import.meta.url).href",
    )
(root / "src/font-catalog.js").write_text(
    "// Generated by scripts/build-font-resources.py from inspected font tables.\n"
    + "export default " + js + ";\n"
)
(destination / "SOURCES.json").write_text(json.dumps(manifest, indent=2) + "\n")
