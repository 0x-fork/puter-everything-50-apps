import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const sourcePath = resolve(root, 'node_modules/opentype.js/dist/opentype.mjs');
const original = readFileSync(sourcePath);
const hash = createHash('sha256').update(original).digest('hex');
if (hash !== 'e139522ac432bb38fb4878d772012f0ad351993c36d7815d65a9890fb3fe68fb')
  throw new Error('OpenType.js source changed; review the upstream version and corrections.');
let source = original.toString('utf8');
function replaceInFunction(name, next, before, after) {
  const start = source.indexOf(`function ${name}(`), end = source.indexOf(`function ${next}(`, start);
  if (start < 0 || end < 0) throw new Error(`Missing function ${name}`);
  const body = source.slice(start, end);
  if (body.split(before).length !== 2) throw new Error(`Unexpected source for ${name}`);
  source = source.slice(0, start) + body.replace(before, after) + source.slice(end);
}
replaceInFunction('MDAP', 'IUP',
  '  fv.setRelative(p, HPZero, d, pv);',
  '  if (round) fv.setRelative(p, HPZero, d, pv);');
replaceInFunction('SDPVTL', 'GETINFO',
  '  state.dpv = getUnitVector(dx, dy);',
  `  state.pv = getUnitVector(dx, dy);
  const ox = p1.xo - p2.xo, oy = p1.yo - p2.yo;
  state.dpv = getUnitVector(a ? -oy : ox, a ? ox : oy);`);
const phantom = 'new HPoint(Math.round(glyph.advanceWidth * xScale), 0)';
if (source.split(phantom).length !== 3) throw new Error('Unexpected phantom construction sites');
source = source.replaceAll(phantom,
  'Object.assign(new HPoint(glyph.advanceWidth * xScale, 0), { x: Math.round(glyph.advanceWidth * xScale) })');
// Remove upstream JSDoc trailing spaces; executable source is untouched.
source = source.replace(/^(\s*\*[^\r\n]*?)[ \t]+$/gm, '$1');
source = '// Generated by tools/generate-opentype-vendor.mjs. See README.md and LICENSE.\n' + source;
const license = readFileSync(resolve(root, 'node_modules/opentype.js/LICENSE'), 'utf8');
if (!license.includes('The MIT License (MIT)') || !license.includes('Copyright (c) 2020 Frederik De Bleser'))
  throw new Error('Unexpected upstream license');
// Preserve the copyright and permission notice in production JS bundles too.
source = `/*!\n${license.trim()}\n*/\n` + source;
const destination = resolve(root, 'src/vendor/opentype');
const publicLicense = resolve(root, 'public/licenses/opentype-MIT.txt');
if (process.argv.includes('--check')) {
  for (const [file, expected] of [['opentype.mjs', source], ['LICENSE', license]])
    if (readFileSync(resolve(destination, file), 'utf8').replaceAll('\r\n', '\n') !== expected.replaceAll('\r\n', '\n'))
      throw new Error(`Vendored ${file} differs from its reproducible source`);
  if (readFileSync(publicLicense, 'utf8').replaceAll('\r\n', '\n') !== license.replaceAll('\r\n', '\n'))
    throw new Error('Missing production OpenType.js license notice');
  console.log('OpenType.js source, three hinting corrections and MIT license verified.');
} else {
  mkdirSync(destination, { recursive: true });
  writeFileSync(resolve(destination, 'opentype.mjs'), source);
  writeFileSync(resolve(destination, 'LICENSE'), license);
  mkdirSync(resolve(root, 'public/licenses'), { recursive: true });
  writeFileSync(publicLicense, license);
}
