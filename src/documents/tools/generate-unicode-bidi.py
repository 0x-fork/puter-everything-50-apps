"""Generate the compact strong-direction table from the pinned Unicode 17 UCD.

Download https://www.unicode.org/Public/17.0.0/ucd/extracted/DerivedBidiClass.txt
then run: python3 tools/generate-unicode-bidi.py /path/to/DerivedBidiClass.txt
"""
from pathlib import Path
import hashlib
import re
import sys

source = Path(sys.argv[1]).read_bytes()
expected = "4867b4b7f0731ed1bfcd34cc6251211ff1542541fce0734b6fbda139ee80b3a4"
if hashlib.sha256(source).hexdigest() != expected:
    raise SystemExit("Expected the unmodified Unicode 17.0.0 DerivedBidiClass.txt")
text = source.decode("utf-8")
values = bytearray([1]) * 0x110000
classes = {"L": 1, "Left_To_Right": 1, "R": 2, "AL": 2, "Right_To_Left": 2, "Arabic_Letter": 2}


def assign(code_range, bidi_class):
    start, *end = code_range.split("..")
    low, high = int(start, 16), int(end[0], 16) if end else int(start, 16)
    values[low:high + 1] = bytes([classes.get(bidi_class, 0)]) * (high - low + 1)


for entry in re.findall(r"@missing:\s*([0-9A-F.]+)\s*;\s*(\w+)", text):
    assign(*entry)
for line in text.splitlines():
    match = re.match(r"^([0-9A-F.]+)\s*;\s*(\w+)", line)
    if match:
        assign(*match.groups())
ranges = []
low = 0
for index in range(1, len(values) + 1):
    if index == len(values) or values[index] != values[low]:
        if values[low] != 1:
            ranges.append(f"0x{low:x}, 0x{index - 1:x}, {values[low]}")
        low = index
rows = ["  " + ", ".join(ranges[index:index + 3]) + "," for index in range(0, len(ranges), 3)]
output = """// Generated by tools/generate-unicode-bidi.py from Unicode 17.0.0.
// Data copyright © 2025 Unicode, Inc. License: public/licenses/unicode-3.0.txt.
// Inclusive ranges: 0 = neither L/R/AL, 2 = R/AL. All other code points are L.
const ranges = [
""" + "\n".join(rows) + """
];

/** First strong Unicode direction, ignoring numbers, marks and punctuation. */
export function firstStrongDirection(text) {
  for (const character of text) {
    const code = character.codePointAt(0);
    let low = 0, high = ranges.length / 3 - 1, value = 1;
    while (low <= high) {
      const middle = (low + high) >>> 1, offset = middle * 3;
      if (code < ranges[offset]) high = middle - 1;
      else if (code > ranges[offset + 1]) low = middle + 1;
      else { value = ranges[offset + 2]; break; }
    }
    if (value) return value === 2 ? 'rtl' : 'ltr';
  }
  return null;
}
"""
target = Path(__file__).resolve().parents[1] / "src/lib/unicode-bidi.js"
target.write_text(output)
print(f"Generated {len(ranges)} ranges in {target.name}")
