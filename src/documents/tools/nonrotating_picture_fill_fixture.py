"""Original nonrotating picture-fill controls; python-docx MIT and lxml BSD.

The quadrant PNG is the original repository asset generated by
canvas_picture_fill_fixture.py. No corpus document content is copied.
"""
from pathlib import Path
from io import BytesIO
from copy import deepcopy
from zipfile import ZipFile, ZIP_DEFLATED
from lxml import etree as E
from canvas_group_fixture import Document, Inches, NS, tag, shape, add

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'tests/fixtures/nonrotating-picture-fill/controls.docx'
CASES = [(angle, flip, False) for angle in [0, 45, 90, 180, 270]
         for flip in [False, True]] + [(180, False, True), (90, False, True)]


def generate():
    with ZipFile(ROOT / 'public/fixtures/shape-picture-fills.docx') as package:
        png = package.read('word/media/image1.png')
    doc = Document()
    doc.settings.element.find(tag('w:zoom')).set(tag('w:percent'), '100')
    section = doc.sections[0]
    section.page_width = section.page_height = Inches(7)
    section.left_margin = section.right_margin = section.top_margin = section.bottom_margin = Inches(1)
    for index, (angle, flip, inset) in enumerate(CASES):
        if index:
            doc.add_page_break()
        doc.add_paragraph(f'Nonrotating fill: rotation {angle}, flipH {flip}, inset {inset}')
        frame = doc.add_paragraph().add_run().add_picture(BytesIO(png), width=Inches(4), height=Inches(3))._inline
        data = frame.find('.//' + tag('a:graphicData'))
        fill = deepcopy(data.find('.//' + tag('pic:blipFill')))
        fill.tag = tag('a:blipFill')
        fill.set('rotWithShape', '0')
        if inset:
            fill.find('.//' + tag('a:fillRect')).attrib.update({'l': '25000', 't': '10000', 'r': '0', 'b': '20000'})
        data.clear()
        data.set('uri', NS['wps'])
        node = shape(data, index+1, 3657600, 2743200, 0, 0, 'FFFFFF', custom=True)
        props = node.find(tag('wps:spPr'))
        props.find(tag('a:xfrm')).set('rot', str(angle*60000))
        if flip:
            props.find(tag('a:xfrm')).set('flipH', '1')
        props.remove(props.find(tag('a:solidFill')))
        props.insert(2, fill)
        frame.tag = tag('wp:anchor')
        for key, value in dict(simplePos='0', relativeHeight=str(index), behindDoc='0', locked='0',
                               layoutInCell='1', allowOverlap='1', distT='0', distB='0', distL='0', distR='0').items():
            frame.set(key, value)
        position = add(frame, 'wp:simplePos', x=0, y=0)
        frame.remove(position)
        frame.insert(0, position)
        for pos_index, axis in enumerate(['H', 'V'], 1):
            position = add(frame, 'wp:position'+axis, relativeFrom='page')
            add(position, 'wp:posOffset', text='1828800')
            frame.remove(position)
            frame.insert(pos_index, position)
        wrapping = add(frame, 'wp:wrapNone')
        frame.remove(wrapping)
        frame.insert(list(frame).index(frame.find(tag('wp:docPr'))), wrapping)
    SOURCE.parent.mkdir(parents=True, exist_ok=True)
    doc.save(SOURCE)
    print(SOURCE)


def generate_groups():
    # Reuse the original, independently reference-verified nested-group geometry.
    with ZipFile(ROOT / 'public/fixtures/group-shape-rotation.docx') as package:
        parts = {name: package.read(name) for name in package.namelist()}
    with ZipFile(ROOT / 'public/fixtures/shape-picture-fills.docx') as package:
        png = package.read('word/media/image1.png')
    relationships = E.fromstring(parts['word/_rels/document.xml.rels'])
    image = next(node for node in relationships if node.get('Type','').endswith('/image'))
    parts['word/'+image.get('Target')] = png
    document = E.fromstring(parts['word/document.xml'])
    count = 0
    for props in document.iter(tag('wps:spPr')):
        solid = props.find(tag('a:solidFill'))
        color = solid.find(tag('a:srgbClr')) if solid is not None else None
        if color is None or color.get('val') != 'E02030':
            continue
        fill = E.Element(tag('a:blipFill'), rotWithShape='0')
        add(fill, 'a:blip', **{'r:embed': image.get('Id')})
        add(add(fill, 'a:stretch'), 'a:fillRect')
        props.replace(solid, fill)
        count += 1
    assert count == 16
    for index, group in enumerate(document.iter(tag('wpg:wgp'))):
        if index < 4:
            group.find(tag('wpg:grpSpPr')+'/'+tag('a:xfrm')).set('rot', str((30 if index < 2 else 90)*60000))
    parts['word/document.xml'] = E.tostring(document, xml_declaration=True, encoding='UTF-8', standalone=True)
    target = SOURCE.with_name('grouped.docx')
    with ZipFile(target, 'w', ZIP_DEFLATED) as package:
        for name, data in parts.items():
            package.writestr(name, data)
    print(target)


if __name__ == '__main__':
    generate()
    generate_groups()
