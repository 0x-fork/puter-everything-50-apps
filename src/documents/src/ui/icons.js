/** Render a Lucide icon as an HTML string. */
/** Whether the outline icon set has this name (menus fall back to the office icons otherwise). */
export const hasIcon = name => Object.hasOwn(ICONS, name);

export function icon(name, size = 20, strokeWidth = 1.8) {
  const node = Object.hasOwn(ICONS, name) ? ICONS[name] : Info;
  const svg = createElement(node);
  svg.setAttribute('width', size);
  svg.setAttribute('height', size);
  svg.setAttribute('stroke-width', strokeWidth);
  svg.setAttribute('aria-hidden', 'true');
  svg.setAttribute('focusable', 'false');
  return svg.outerHTML;
}

/** Same, as a live SVG element. */
export function iconEl(name, size = 20, strokeWidth = 1.8) {
  const tpl = document.createElement('template');
  tpl.innerHTML = icon(name, size, strokeWidth);
  return tpl.content.firstElementChild;
}

