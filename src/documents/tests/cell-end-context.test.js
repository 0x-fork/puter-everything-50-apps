import {beforeAll,afterAll,it,expect} from 'vitest';
import {JSDOM} from 'jsdom';
import {readFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {unzipSync} from 'fflate';
import {DocxPackage} from '../src/engine/docx.js';
import {TextDocument} from '../src/engine/model.js';
import {layoutDocument} from '../src/engine/layout.js';
import {pageGeometry} from '../src/engine/page-settings.js';
const folder='tests/fixtures/cell-end-context',refs=JSON.parse(readFileSync(`${folder}/reference.json`));
let dom;beforeAll(()=>{dom=new JSDOM();globalThis.DOMParser=dom.window.DOMParser;globalThis.XMLSerializer=dom.window.XMLSerializer;});afterAll(()=>{dom.window.close();delete globalThis.DOMParser;delete globalThis.XMLSerializer;});
const layout=d=>layoutDocument(d.paragraphs,(t,s)=>({width:t.length*s.fontSize/2,ascent:s.fontSize,descent:s.fontSize/4}),pageGeometry(d.pageSettings),d.numbering,d.tables);
it('retains native source and PDF hashes',()=>{for(const ref of Object.values(refs))for(const[n,h]of Object.entries(ref.hashes))expect(createHash('sha256').update(readFileSync(`${folder}/${n}`)).digest('hex')).toBe(h);});
for(const name of ['control','default','id','name'])it(`${name}: resolves the cell-ending style and preserves edit/export/undo`,async()=>{
 const source=readFileSync(`${folder}/${name}.docx`),p=await DocxPackage.open(source),d=new TextDocument(p.paragraphs,p.pageSettings,p.numbering,p.styles,p.tables,p.assets);
 const heights=(doc=d)=>{const cells=layout(doc).cells;return doc.tables.map(t=>cells.find(c=>c.id===t.rows[0].cells[0].id).height*.75);},before=heights();
 const normal=name==='control'||name==='id';
 const expected=normal?[28,28,44,44,28,28,44,44]:[36,36,44,44,36,36,44,44]; before.slice(0,8).forEach((h,i)=>expect(h).toBeCloseTo(expected[i],6));
 const tail=normal?[14,22,44,36]:name==='default'?[22,22,36,36]:[22,22,44,44]; before.slice(8).forEach((h,i)=>expect(h).toBeCloseTo(tail[i],6));
 d.selectCell(d.tables[0].rows[0].cells[0].id);d.setParagraphStyle('Other');
 expect(heights()[0]).toBeCloseTo(name==='name'?44:36,6);
 const save=async()=>new Uint8Array(await p.export(d.paragraphs,d.pageSettings,d.numbering,d.styles,d.tables,d.assets).arrayBuffer());
 const edited=await save(),reopened=await DocxPackage.open(edited);
 expect(heights(reopened)).toEqual(heights());
 const original=unzipSync(source),out=unzipSync(edited);
 for(const n of Object.keys(original))if(n!=='word/document.xml')expect(Buffer.from(out[n]).equals(Buffer.from(original[n])),n).toBe(true);
 d.undo();expect(heights()).toEqual(before);
 const undo=unzipSync(await save());for(const n of Object.keys(original))expect(Buffer.from(undo[n]).equals(Buffer.from(original[n])),n).toBe(true);
});
