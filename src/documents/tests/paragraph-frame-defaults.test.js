import {beforeAll,afterAll,it,expect} from 'vitest';
import {JSDOM} from 'jsdom';
import {readFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {unzipSync} from 'fflate';
import {DocxPackage} from '../src/engine/docx.js';
import {TextDocument} from '../src/engine/model.js';
import {frameDimensions} from '../src/engine/paragraph-frames.js';
import {layoutDocument} from '../src/engine/layout.js';
import {pageGeometry} from '../src/engine/page-settings.js';
const root='tests/fixtures/frame-default-compatibility/';
const cases=JSON.parse(readFileSync(root+'cases.json','utf8'));
let dom;
beforeAll(()=>{dom=new JSDOM();globalThis.DOMParser=dom.window.DOMParser;globalThis.XMLSerializer=dom.window.XMLSerializer;});
afterAll(()=>{dom.window.close();delete globalThis.DOMParser;delete globalThis.XMLSerializer;});
for(const [name,properties] of Object.entries(cases)) it(`${name}: native default evidence, retained attributes, editing and undo`,async()=>{
  const bytes=readFileSync(root+name+'.docx'),native=JSON.parse(readFileSync(root+name+'-native.json','utf8').replace(/^\uFEFF/,''));
  expect(createHash('sha256').update(bytes).digest('hex')).toBe(native.sourceSha256);
  expect(native.frames).toHaveLength(1);expect(native.pages).toBe(1);
  expect(native.frames[0].horizontalBase).toBe(properties.hAnchor==='page'?1:2);
  expect(native.frames[0].verticalBase).toBe(properties.vAnchor==='page'?1:2);
  const fixedHeight=['minimum-height','explicit-minimum'].includes(name)?72:name==='short-minimum'?6:name.startsWith('absent-')?Number(properties.w||2400)/20:-1;
  expect(native.frames[0].height).toBe(fixedHeight);
  const pkg=await DocxPackage.open(bytes);
  const d=new TextDocument(pkg.paragraphs,pkg.pageSettings,pkg.numbering,pkg.styles,pkg.tables,pkg.assets);
  const layout=()=>layoutDocument(d.paragraphs,text=>({width:text.length*6,ascent:12,descent:4}),pageGeometry(d.pageSettings),d.numbering,d.tables);
  const before=layout();expect(before.paragraphFrames).toHaveLength(1);
  const frame=before.paragraphFrames[0];
  expect(frame.left*.75).toBe(properties.hAnchor==='page'?144:72);
  expect(frame.top*.75).toBe(properties.vAnchor==='page'?72:84);
  expect(frame.bottom-frame.top).toBe(fixedHeight>12?fixedHeight/.75:16);
  expect(d.paragraphs[1].frameProperties).toEqual(Object.fromEntries(Object.entries({w:'2400',wrap:'none',...properties}).filter(([,value])=>value!==null)));
  const save=async()=>new Uint8Array(await pkg.export(d.paragraphs,d.pageSettings,d.numbering,d.styles,d.tables,d.assets).arrayBuffer());
  expect(unzipSync(await save())).toEqual(unzipSync(bytes));
  d.select(d.text.indexOf('Framed first line')+7);d.replace('Edited ');
  const output=await save(),again=await DocxPackage.open(output);
  expect(again.paragraphs[1].frameProperties).toEqual(pkg.paragraphs[1].frameProperties);
  expect(again.paragraphs[1].runs.map(r=>r.text).join('')).toContain('Edited ');
  for(const [part,content] of Object.entries(unzipSync(bytes)))if(part!=='word/document.xml')expect(unzipSync(output)[part]).toEqual(content);
  d.undo();expect(layout().lines).toEqual(before.lines);expect(unzipSync(await save())).toEqual(unzipSync(bytes));
});
it('defaults retain validation and explicit anchor/height behavior',()=>{
  expect(()=>frameDimensions({hRule:'invalid',h:'0'})).toThrow();
  expect(()=>frameDimensions({h:'-1'})).toThrow();
  expect(frameDimensions({h:'1440',hRule:'exact',hAnchor:'page',vAnchor:'margin'})).toMatchObject({hRule:'exact',hAnchor:'page',vAnchor:'margin',height:96});
  expect(frameDimensions({h:'1440',hRule:'auto'}).hRule).toBe('auto');
});
