import {beforeAll,afterAll,it,expect} from 'vitest';
import {JSDOM} from 'jsdom';
import {readFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {unzipSync} from 'fflate';
import {DocxPackage} from '../src/engine/docx.js';
import {TextDocument} from '../src/engine/model.js';
import {layoutDocument,caretRect} from '../src/engine/layout.js';
import {pageGeometry} from '../src/engine/page-settings.js';
const root='tests/fixtures/leading-break-indent/',reference=JSON.parse(readFileSync(root+'reference.json'));
let dom;
beforeAll(()=>{dom=new JSDOM();globalThis.DOMParser=dom.window.DOMParser;globalThis.XMLSerializer=dom.window.XMLSerializer;});
afterAll(()=>{dom.window.close();delete globalThis.DOMParser;delete globalThis.XMLSerializer;});
const measure=(text,style)=>({width:text.length*style.fontSize/2,ascent:style.fontSize,descent:style.fontSize/4});
const model=p=>new TextDocument(p.paragraphs,p.pageSettings,p.numbering,p.styles,p.tables,p.assets);
const layout=d=>layoutDocument(d.paragraphs,measure,pageGeometry(d.pageSettings),d.numbering,d.tables);
const save=async(p,d)=>new Uint8Array(await p.export(d.paragraphs,d.pageSettings,d.numbering,d.styles,d.tables,d.assets).arrayBuffer());
it.each(reference.cases)('matches native first text indentation after $name breaks',async ref=>{
 const source=readFileSync(root+ref.name+'.docx');
 for(const[bytes,hash]of [[source,ref.sourceSha256],[readFileSync(root+ref.name+'-native.pdf'),ref.pdfSha256]])expect(createHash('sha256').update(bytes).digest('hex')).toBe(hash);
 const p=await DocxPackage.open(source),d=model(p),l=layout(d),position=d.text.indexOf('START');
 const first=l.lines.find(line=>line.start<=position&&line.end>position);
 expect(first.page).toBe(ref.first.page);expect(l.pageCount).toBe(ref.pages);
 expect(Math.abs(caretRect(l,position).x*.75-ref.first.x)).toBeLessThan(.1);
 const continuation=l.lines.find(line=>line.paragraphId===first.paragraphId&&line.start>first.start&&!line.hardBreak);
 expect(continuation.fragments[0].x*.75).toBeCloseTo(108,5);
 d.select(position+6);d.replace('Edited ');const exported=await save(p,d),again=model(await DocxPackage.open(exported));expect(again.text).toBe(d.text);
 expect(Math.abs(caretRect(layout(again),again.text.indexOf('START')).x*.75-ref.first.x)).toBeLessThan(.1);
 for(const[name,bytes]of Object.entries(p.parts))if(name!=='word/document.xml')expect(unzipSync(exported)[name]).toEqual(bytes);
 d.undo();expect(unzipSync(await save(p,d))).toEqual(p.parts);
});
