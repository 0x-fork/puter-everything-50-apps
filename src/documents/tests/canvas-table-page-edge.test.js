import {beforeAll,afterAll,it,expect} from 'vitest';
import {JSDOM} from 'jsdom';
import {readFileSync} from 'node:fs';
import {unzipSync} from 'fflate';
import {DocxPackage} from '../src/engine/docx.js';
import {TextDocument,paragraph} from '../src/engine/model.js';
import {layoutDocument,caretRect,selectionRects,hitTest,imageAtPoint} from '../src/engine/layout.js';
import {intersectCellClip,shiftCellClip} from '../src/engine/cell-clipping.js';
import {pageGeometry} from '../src/engine/page-settings.js';
import {emptyNumbering,newList} from '../src/engine/numbering.js';
let dom;
beforeAll(()=>{dom=new JSDOM();globalThis.DOMParser=dom.window.DOMParser;globalThis.XMLSerializer=dom.window.XMLSerializer;});
afterAll(()=>{dom.window.close();delete globalThis.DOMParser;delete globalThis.XMLSerializer;});
const measure=text=>({width:text.length*8,ascent:12,descent:4});
const targets=p=>p.tables.filter(t=>t.rows[0].cells[0].fill==='#336699');
const layout=p=>layoutDocument(p.paragraphs,measure,pageGeometry(p.pageSettings),p.numbering,p.tables);
for(const suffix of ['','-legacy'])it(`retains page-edge table geometry, edits and undo${suffix}`,async()=>{
 const source=readFileSync(`public/fixtures/table-page-edge${suffix}.docx`),p=await DocxPackage.open(source),tables=targets(p),ref=JSON.parse(readFileSync(`tests/fixtures/table-page-edge/reference${suffix}.json`));
 expect(tables).toHaveLength(9);const placed=layout(p);
 tables.forEach((t,i)=>t.rows[0].cells.forEach((c,j)=>{const box=placed.cells.find(b=>b.id===c.id),expected=ref.cases[i].cells[j];if(expected)for(const [key,value]of [['x',expected.left],['width',expected.width]])expect(Math.abs(box[key]*.75-value)).toBeLessThan(.2);}));
 expect(placed.cells.find(c=>c.id===tables[4].rows[0].cells[1].id).x).toBeLessThan(0);
 expect(placed.cells.find(c=>c.id===tables[5].rows[0].cells[0].id).x).toBeGreaterThan(816);
 const d=new TextDocument(p.paragraphs,p.pageSettings,p.numbering,p.styles,p.tables,p.assets);
 const save=async()=>new Uint8Array(await p.export(d.paragraphs,d.pageSettings,d.numbering,d.styles,d.tables,d.assets).arrayBuffer());
 expect(unzipSync(await save())).toEqual(p.parts);d.select(0);d.replace('Edited ');
 const hidden=d.text.indexOf('\nA',d.text.indexOf('Page-edge tables: fully left'))+1;
 expect(hidden).toBeGreaterThan(0);d.select(hidden);d.replace('Hidden cell edit ');
 const edited=await save(),reopened=await DocxPackage.open(edited);
 expect(reopened.paragraphs.some(p=>p.runs.some(r=>r.text.includes('Hidden cell edit')))).toBe(true);
 expect(targets(reopened).map(t=>[t.indent,t.width,t.grid])).toEqual(tables.map(t=>[t.indent,t.width,t.grid]));
 expect(()=>layout(reopened)).not.toThrow();for(const[n,b]of Object.entries(unzipSync(edited)))if(n!=='word/document.xml')expect(b).toEqual(p.parts[n]);
 d.undo();d.undo();expect(unzipSync(await save())).toEqual(p.parts);
});
it.each([false,true])('lays out numbered off-page cells and signed body indents (legacy=%s)',async legacy=>{
 const p=await DocxPackage.open(readFileSync('public/fixtures/table-page-edge.docx'));
 const numbering=emptyNumbering(),numId=newList(numbering,'number');
 if(legacy)numbering.abstracts[1].levels[0].legacy={indent:-120,space:0};
 const c=targets(p)[4].rows[0].cells[0],para=p.paragraphs.find(p=>p.cellId===c.id);para.list={numId,level:0};
 expect(()=>layoutDocument(p.paragraphs,measure,pageGeometry(p.pageSettings),numbering,p.tables)).not.toThrow();
 const body=paragraph('Body',{format:{indentLeft:-5000}});
 const placed=layoutDocument([body],measure,pageGeometry(p.pageSettings),numbering);
 expect(placed.lines[0].stops[0].x).toBeLessThan(0);
 expect(caretRect(placed,0).x).toBe(0);
});

it('shares horizontal nested clipping between painting geometry and interaction',async()=>{
 const p=await DocxPackage.open(readFileSync('public/fixtures/table-page-edge.docx')),placed=layout(p);
 const cell=targets(p)[7].rows[0].cells[1],line=placed.lines.find(l=>l.cellId===cell.id);
 expect(line.stops[0].x).toBeGreaterThan(line.cellClip.right);
 expect(selectionRects(placed,line.start,line.end)).toEqual([]);
 expect(caretRect(placed,line.start).x).toBeLessThan(line.cellClip.right);
 const at=hitTest(placed,line.page,line.stops[0].x+1,line.y+2);
 expect(at<line.start||at>line.end).toBe(true);
 const floating={page:line.page,x:line.stops[0].x,y:line.y,width:10,height:10,cellClip:line.cellClip};
 expect(imageAtPoint({...placed,floatingObjects:[floating]},line.page,floating.x+2,floating.y+2)).toBeNull();
 const shifted=shiftCellClip(line.cellClip,10);expect(shifted.left).toBe(line.cellClip.left);expect(shifted.right).toBe(line.cellClip.right);
 const intersection=intersectCellClip({left:300,right:400,top:0,bottom:30},{left:100,right:200,top:10,bottom:20});
 expect(intersection).toEqual({left:200,right:200,top:10,bottom:20});
});
