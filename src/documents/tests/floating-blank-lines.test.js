import { beforeAll, afterAll, it, expect } from 'vitest';
import { JSDOM } from 'jsdom';
import { readFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { unzipSync } from 'fflate';
import { DocxPackage } from '../src/engine/docx.js';
import { TextDocument } from '../src/engine/model.js';
import { layoutDocument } from '../src/engine/layout.js';
import { pageGeometry } from '../src/engine/page-settings.js';
import { expectBodyEditParts } from './helpers/expect-body-edit-parts.js';
const root='tests/fixtures/floating-blank-lines/';
let dom;
beforeAll(()=>{dom=new JSDOM();globalThis.DOMParser=dom.window.DOMParser;globalThis.XMLSerializer=dom.window.XMLSerializer;});
afterAll(()=>{dom.window.close();delete globalThis.DOMParser;delete globalThis.XMLSerializer;});
const measure=(text,style)=>({width:text.length*4,ascent:style.fontSize,descent:style.fontSize/3});
const layout=doc=>layoutDocument(doc.paragraphs,measure,pageGeometry(doc.pageSettings));
it('pins the independent reference capture and proves floating blank spaces retain mark height',()=>{
 const ref=JSON.parse(readFileSync(root+'reference.json'));
 for(const [file,hash] of [['source.docx',ref.sourceSha256],['native.pdf',ref.pdfSha256]])expect(createHash('sha256').update(readFileSync(root+file)).digest('hex')).toBe(hash);
 expect(ref.pages).toHaveLength(16);
 for(let i=0;i<8;i++)expect(ref.pages[i+8].After).toBeCloseTo(ref.pages[i].After,6);
 for(const i of [1,2,3])expect(ref.pages[i].After).toBe(ref.pages[0].After);
 for(const i of [4,5,6,7])expect(ref.pages[i].After-ref.pages[0].After).toBeGreaterThan(10);
});
it('keeps floating spaces editable and updates line height when replaced by NBSP',async()=>{
 const pkg=await DocxPackage.open(readFileSync(root+'source.docx'));
 const doc=new TextDocument(pkg.paragraphs,pkg.pageSettings,pkg.numbering,pkg.styles,pkg.tables,pkg.assets);
 const save=async()=>new Uint8Array(await pkg.export(doc.paragraphs,doc.pageSettings,doc.numbering,doc.styles,doc.tables,doc.assets).arrayBuffer());
 const after=(l,page)=>l.lines.find(line=>line.page===page&&line.fragments.map(f=>f.text).join('')==='After').baseline;
 const original=layout(doc);
 for(let i=0;i<8;i++)expect(after(original,i+8)).toBeCloseTo(after(original,i),8);
 const index=38, p=doc.paragraphs[index];
 expect(p.runs.map(r=>r.text).join('')).toBe('\ufffc ');
 const offset=doc.paragraphs.slice(0,index).reduce((n,p)=>n+p.runs.reduce((n,r)=>n+r.text.length,0)+1,0)+1;
 doc.select(offset,offset+1);doc.replace('\u00a0');
 expect(after(layout(doc),9)-after(original,9)).toBeGreaterThan(10);
 const edited=await save(), parts=unzipSync(edited), reopened=await DocxPackage.open(edited);
 expect(reopened.paragraphs[index].runs.map(r=>r.text).join('')).toBe('\ufffc\u00a0');
 expectBodyEditParts(parts,pkg.parts);
 doc.undo();expect(after(layout(doc),9)).toBe(after(original,9));
 const undo=unzipSync(await save());for(const name in pkg.parts)expect(undo[name]).toEqual(pkg.parts[name]);
},60000);
