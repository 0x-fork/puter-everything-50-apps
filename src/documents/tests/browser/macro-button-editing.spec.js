import {test,expect} from '@playwright/test';
import {readFileSync} from 'node:fs';
import {unzipSync} from 'fflate';
import {showAllTools} from './helpers/editor-tools.js';
import {reopenDocx} from './helpers/reopen-docx.js';
const source='tests/fixtures/macro-buttons/editing.docx';
test('selects prompts atomically, replaces them, formats retained instructions and reopens editable exports',async({page},info)=>{
 test.setTimeout(180000);const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/playground.html');await showAllTools(page);await page.getByLabel('Open DOCX file').setInputFiles(source);
 const input=page.getByRole('textbox',{name:'Document text'});
 await expect(input).toHaveValue(/^Unquoted: \[Last, First Name of Author\]/);await expect(input).toHaveJSProperty('readOnly',false);
 await expect(page.locator('canvas.canvas-page')).toHaveCount(1);
 const original=await input.inputValue(),parts=unzipSync(readFileSync(source));
 const choose=async(a,b=a)=>input.evaluate((el,{a,b})=>{el.focus();el.setSelectionRange(a,b);el.dispatchEvent(new Event('select',{bubbles:true}));},{a,b});
 const save=async name=>{const pending=page.waitForEvent('download');await page.getByRole('button',{name:'Download .docx',exact:true}).click();const path=info.outputPath(name+'.docx');await(await pending).saveAs(path);return path;};
 const reopen=async(path,text)=>{page.removeAllListeners('dialog');await reopenDocx(page,input,path,text);await expect(input).toHaveJSProperty('readOnly',false);};
 const start=original.indexOf('[Last'),end=original.indexOf(']')+1;
 await choose(start);await input.press('ArrowRight');expect(await input.evaluate(el=>el.selectionStart)).toBe(end);
 await input.press('Shift+ArrowLeft');expect(await input.evaluate(el=>[el.selectionStart,el.selectionEnd])).toEqual([start,end]);
 await page.keyboard.insertText('Author');const replaced=original.slice(0,start)+'Author'+original.slice(end);await expect(input).toHaveValue(replaced);
 const output=await save('replaced');await page.getByRole('button',{name:'Undo',exact:true}).click();await expect(input).toHaveValue(original);
 expect(unzipSync(readFileSync(await save('undo')))).toEqual(parts);await reopen(output,replaced);await reopen(source,original);
 const simple=original.indexOf('Simple display');await choose(simple+2);
 expect(await input.evaluate(el=>[el.selectionStart,el.selectionEnd])).toEqual([simple,simple+'Simple display'.length]);
 await page.getByRole('button',{name:'Italic',exact:true}).click();await expect(input).toHaveValue(original);
 const formatted=await save('formatted');await reopen(formatted,original);await choose(simple+2);
 await expect(page.getByRole('button',{name:'Italic',exact:true})).toHaveAttribute('aria-pressed','true');
 await input.press('Delete');await expect(input).toHaveValue(original.replace('Simple display',''));
 const deleted=await save('deleted');await reopen(deleted,original.replace('Simple display',''));
 for(const path of [output,formatted,deleted])for(const[name,bytes]of Object.entries(parts))if(name!=='word/document.xml')expect(unzipSync(readFileSync(path))[name]).toEqual(bytes);
 expect(errors).toEqual([]);
});
