import { test, expect } from '@playwright/test';
import { downloadDocx } from './helpers/editor-tools.js';
import { reopenDocx } from './helpers/reopen-docx.js';
import { readFileSync } from 'node:fs';
import { unzipSync } from 'fflate';

const redPixels = page => page.locator('canvas.canvas-page').first().evaluate(c => {
  const data = c.getContext('2d').getImageData(0, 0, c.width, c.height).data;
  let count = 0;
  for (let i = 0; i < data.length; i += 4) if (data[i] > 150 && data[i + 1] < 100 && data[i + 2] < 100) count++;
  return count;
});
for (const [name, hidden] of [['implicit', true], ['off', false]]) test(`${name}: automatic marks respect the document while manual review, undo and reopen work`, async ({ page }, info) => {
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto('/playground.html');
  await page.getByLabel('Open DOCX file').setInputFiles(`tests/fixtures/hidden-spelling/${name}.docx`);
  const input = page.getByRole('textbox', { name: 'Document text' });
  await expect(input).toHaveValue('Teh quick fox jumpd.');
  await expect(page.locator('.ed-proofing')).toHaveAttribute('aria-label', /2 errors found/);
  if (hidden) expect(await redPixels(page)).toBe(0);
  else expect(await redPixels(page)).toBeGreaterThan(0);
  await input.evaluate(el => { el.focus(); el.setSelectionRange(1, 1); el.dispatchEvent(new Event('select', { bubbles: true })); });
  const caret = await input.evaluate(el => ({ left: parseFloat(el.style.left), top: parseFloat(el.style.top), height: parseFloat(el.style.height) }));
  const surface = await page.locator('.canvas-pages').boundingBox();
  await page.mouse.click(surface.x + caret.left, surface.y + caret.top + caret.height / 2, { button: 'right' });
  const menu = page.getByRole('menu', { name: 'Document menu' });
  if (hidden) await expect(menu.getByRole('menuitem', { name: 'Ignore All', exact: true })).toHaveCount(0);
  else await expect(menu.getByRole('menuitem', { name: 'Ignore All', exact: true })).toBeVisible();
  await page.keyboard.press('Escape');
  await input.press('ControlOrMeta+Home'); await input.press('F7');
  const pane = page.getByRole('complementary', { name: 'Spelling' });
  await expect(pane.locator('mark')).toHaveText('Teh');
  await expect(pane.getByRole('option').first()).toHaveText('The');
  await pane.getByRole('button', { name: 'Change', exact: true }).click();
  await expect(input).toHaveValue('The quick fox jumpd.');
  await page.getByRole('button', { name: 'Close Spelling pane' }).click();
  const path = info.outputPath(`${name}-edited.docx`), pending = page.waitForEvent('download');
  await downloadDocx(page); await (await pending).saveAs(path);
  const original = unzipSync(readFileSync(`tests/fixtures/hidden-spelling/${name}.docx`));
  expect(unzipSync(readFileSync(path))['word/settings.xml']).toEqual(original['word/settings.xml']);
  await input.press('ControlOrMeta+z'); await expect(input).toHaveValue('Teh quick fox jumpd.');
  const undoPath = info.outputPath(`${name}-undo.docx`), undoPending = page.waitForEvent('download');
  await downloadDocx(page); await (await undoPending).saveAs(undoPath);
  const undone = unzipSync(readFileSync(undoPath));
  expect(Object.keys(undone).sort()).toEqual(Object.keys(original).sort());
  for (const part of Object.keys(original)) expect(undone[part], part).toEqual(original[part]);
  await reopenDocx(page, input, path, 'The quick fox jumpd.');
  await expect(page.locator('.ed-proofing')).toHaveAttribute('aria-label', /1 error found/);
  if (hidden) expect(await redPixels(page)).toBe(0);
  else expect(await redPixels(page)).toBeGreaterThan(0);
  expect(errors).toEqual([]);
});
