import { beforeAll,afterAll,it,expect } from 'vitest';
import {JSDOM} from 'jsdom';
import {readFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {unzipSync,strFromU8} from 'fflate';
import {DocxPackage} from '../src/engine/docx.js';
import {TextDocument} from '../src/engine/model.js';
import {layoutDocument} from '../src/engine/layout.js';
import {pageGeometry} from '../src/engine/page-settings.js';
const folder='tests/fixtures/column-count/';
const refs=JSON.parse(readFileSync(folder+'reference.json','utf8'));
let dom;
beforeAll(()=>{dom=new JSDOM();for(const n of ['Node','document','DOMParser','XMLSerializer'])globalThis[n]=dom.window[n];});
afterAll(()=>{dom.window.close();for(const n of ['Node','document','DOMParser','XMLSerializer'])delete globalThis[n];});
for(const [name,ref] of Object.entries(refs).filter(([n])=>!n.endsWith('num3')))it(`${name} follows the native reference count precedence and preserves surplus source entries`,async()=>{
 const bytes=readFileSync(folder+name+'.docx');expect(createHash('sha256').update(bytes).digest('hex')).toBe(ref.sha256);
 const p=await DocxPackage.open(bytes);expect(p.readOnly).not.toBe(true);
 expect(p.pageSettings.columns.count).toBe(ref.columns.length);
 expect(p.pageSettings.columns.entries.map(c=>c.width/20)).toEqual(ref.columns.map(c=>c.width));
 const doc=new TextDocument(p.paragraphs,p.pageSettings,p.numbering,p.styles,p.tables,p.assets);
 const layout=layoutDocument(doc.paragraphs,t=>({width:t.length*6,ascent:12,descent:4}),pageGeometry(doc.pageSettings),doc.numbering,doc.tables);
 expect(layout.pageCount).toBe(ref.pages);
 const rows=layout.lines.filter(l=>l.fragments.some(f=>f.text)).map(l=>({text:l.fragments.map(f=>f.text||'').join(''),page:l.page+1,x:l.stops[0].x*.75}));
 expect(rows).toEqual(ref.rows.map(({text,page,x})=>({text,page,x})));
 const save=async()=>new Uint8Array(await p.export(doc.paragraphs,doc.pageSettings,doc.numbering,doc.styles,doc.tables,doc.assets).arrayBuffer());
 expect(unzipSync(await save())).toEqual(unzipSync(bytes));
 doc.select(0);doc.replace('EDIT ');const edited=unzipSync(await save());
 const originalCols=strFromU8(p.parts['word/document.xml']).match(/<w:cols\b[\s\S]*?<\/w:cols>/)[0];
 expect(strFromU8(edited['word/document.xml'])).toContain(originalCols);
 const reopened=await DocxPackage.open(await save());expect(reopened.pageSettings.columns).toEqual(p.pageSettings.columns);
 doc.undo();expect(unzipSync(await save())).toEqual(unzipSync(bytes));
});
