import { beforeAll, afterAll, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { JSDOM } from 'jsdom';
import { DocxPackage } from '../src/engine/docx.js';
import { TextDocument } from '../src/engine/model.js';
let dom;
beforeAll(() => { dom = new JSDOM(); globalThis.DOMParser = dom.window.DOMParser; globalThis.XMLSerializer = dom.window.XMLSerializer; });
afterAll(() => dom.window.close());
const model = pkg => new TextDocument(pkg.paragraphs, pkg.pageSettings, pkg.numbering, pkg.styles, pkg.tables, pkg.assets);
const save = async (pkg, doc) => new Uint8Array(await pkg.export(doc.paragraphs, doc.pageSettings, doc.numbering, doc.styles, doc.tables, doc.assets).arrayBuffer());
it.each([false, true])('inserts a paragraph beside the whole nested subtree in the parent cell (after: %s)', async after => {
  const pkg = await DocxPackage.open(readFileSync('tests/fixtures/nested-tables/nested-table-deep.docx')), doc = model(pkg);
  const original = doc.text;
  doc.select(doc.text.indexOf('Inner B1'));
  const child = doc.tableContext.table, parent = child.parentCellId;
  doc.insertTableParagraph(after);
  const selected = doc.paragraphs.find(p => doc.paragraphOffset(doc.paragraphs.indexOf(p)) === doc.range[0]);
  expect(selected.cellId).toBe(parent);
  const index = doc.paragraphs.indexOf(selected);
  expect(doc.paragraphs[index + (after ? -1 : 1)].runs.map(r => r.text).join('')).toBe(after ? 'Inner B2' : 'Deep cell');
  doc.replace(after ? 'After inner' : 'Before inner');
  const reopened = model(await DocxPackage.open(await save(pkg, doc)));
  expect(reopened.text).toBe(doc.text); expect(reopened.tables).toHaveLength(3);
  const added = reopened.paragraphs.find(p => p.runs.some(r => r.text === (after ? 'After inner' : 'Before inner')));
  expect(reopened.tables.find(t => t.parentCellId === added.cellId)).toBeTruthy();
  doc.undo(); doc.undo(); expect(doc.text).toBe(original);
  doc.redo(); doc.redo(); expect(doc.text).toBe(reopened.text);
});
it('resolves merge selection to the nearest shared row and rejects unrelated rows and body text', async () => {
  const pkg = await DocxPackage.open(readFileSync('tests/fixtures/nested-tables/nested-table-deep.docx')), doc = model(pkg);
  const select = (first, last) => doc.select(doc.text.indexOf(first), doc.text.indexOf(last) + last.length);
  const outer = doc.tables.find(t => !t.parentCellId), child = doc.tables.find(t => t.parentCellId === outer.rows[0].cells[0].id);
  select('Deep cell', 'Inner B1'); expect(doc.mergeCellsContext.table.id).toBe(child.id);
  select('Deep cell', 'Outer side'); expect(doc.mergeCellsContext.table.id).toBe(outer.id);
  select('Inner B1', 'Inner A2'); expect(doc.mergeCellsContext).toBeNull();
  select('Outer side', 'Outer lower left'); expect(doc.mergeCellsContext).toBeNull();
  select('Deep cell', 'After outer table'); expect(doc.mergeCellsContext).toBeNull();
  select('Deep cell', 'Inner A1'); expect(doc.mergeCellsContext).toBeNull();
});
