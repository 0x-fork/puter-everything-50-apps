/** Returns an inline SVG element for a registered Lucide icon. */
export function icon(name, size = 18) {
  const node = REGISTRY[name];
  if (!node) throw new Error(`Unknown icon: ${name}`);
  return createElement(node, {
    class: 'icon',
    width: size,
    height: size,
    'stroke-width': 2,
    'aria-hidden': 'true',
  });
}
