const templates = new Map();

/** A fresh SVG element. Unknown names fall back to a circle (and warn in dev). */
export function icon(name, size = 18, extraClass = '') {
  let tpl = templates.get(name);
  if (!tpl) {
    const def = REGISTRY[name];
    if (!def && import.meta.env?.DEV) console.warn(`[legal] unknown icon "${name}"`);
    tpl = createElement(def || Circle);
    tpl.setAttribute('aria-hidden', 'true');
    tpl.setAttribute('focusable', 'false');
    tpl.removeAttribute('width');
    tpl.removeAttribute('height');
    templates.set(name, tpl);
  }
  const node = tpl.cloneNode(true);
  node.setAttribute('class', `icon${extraClass ? ' ' + extraClass : ''}`);
  node.style.width = `${size}px`;
  node.style.height = `${size}px`;
  return node;
}

export const ICON_NAMES = Object.keys(REGISTRY);
