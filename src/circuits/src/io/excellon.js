// Excellon drill files: one for plated holes (vias and plated pads) and one
// for non-plated holes. Metric, absolute, decimal coordinates.

import { resolveBoard, SOFTWARE, SOFTWARE_VERSION } from './gerber.js';
import { baseName } from './common.js';

const mm3 = (nm) => (nm / 1e6).toFixed(3);

/** Collects drill hits: [{ x, y, d, plated }]. */
export function collectHoles(boardDoc, library) {
  const ctx = resolveBoard(boardDoc, library);
  const holes = [];
  for (const { placed } of ctx.comps) {
    for (const pad of placed.pads) {
      if (pad.side === 'thru' && pad.drill > 0) holes.push({ x: pad.x, y: pad.y, d: pad.drill, plated: pad.plated !== false });
    }
  }
  for (const o of ctx.objects) {
    if (o.t === 'via' && o.drill > 0) holes.push({ x: o.x, y: o.y, d: o.drill, plated: true });
    else if (o.t === 'pad' && o.side === 'thru' && o.drill > 0) holes.push({ x: o.x, y: o.y, d: o.drill, plated: o.plated !== false });
  }
  return { holes, origin: ctx.origin, copper: ctx.copper };
}

/** Writes one Excellon file for the given holes. */
export function excellonFile(holes, { origin = { x: 0, y: 0 }, plated = true, copper = 2 } = {}) {
  // Group by diameter, rounded to a micrometre so equal tools merge.
  const tools = new Map();
  for (const h of holes) {
    const d = Math.round(h.d / 1000) * 1000;
    if (!tools.has(d)) tools.set(d, []);
    tools.get(d).push(h);
  }
  const sizes = [...tools.keys()].sort((a, b) => a - b);
  const lines = [
    'M48',
    `; Drill file generated by ${SOFTWARE} ${SOFTWARE_VERSION}`,
    '; FORMAT={-:-/ absolute / metric / decimal}',
    `; #@! TF.FileFunction,${plated ? `Plated,1,${copper},PTH` : `NonPlated,1,${copper},NPTH`}`,
    'FMAT,2',
    'METRIC',
  ];
  sizes.forEach((d, i) => lines.push(`T${i + 1}C${mm3(d)}`));
  lines.push('%', 'G90', 'G05');
  sizes.forEach((d, i) => {
    lines.push(`T${i + 1}`);
    const list = tools.get(d).slice().sort((a, b) => a.x - b.x || a.y - b.y);
    for (const h of list) lines.push(`X${mm3(h.x - origin.x)}Y${mm3(h.y - origin.y)}`);
  });
  lines.push('M30');
  return lines.join('\n') + '\n';
}

/**
 * Exports the plated and non-plated drill files (a file is left out when it
 * would have no holes).
 * @returns {{name:string, plated:boolean, content:string, count:number}[]}
 */
export function exportDrill(boardDoc, library, opts = {}) {
  const { holes, origin, copper } = collectHoles(boardDoc, library);
  const name = baseName(opts.boardName || boardDoc.name);
  const out = [];
  const pth = holes.filter((h) => h.plated), npth = holes.filter((h) => !h.plated);
  if (pth.length || !npth.length) out.push({ name: `${name}-PTH.drl`, plated: true, content: excellonFile(pth, { origin, plated: true, copper }), count: pth.length });
  if (npth.length) out.push({ name: `${name}-NPTH.drl`, plated: false, content: excellonFile(npth, { origin, plated: false, copper }), count: npth.length });
  return out;
}
