// Plain text netlist export.

import { naturalCompare } from './common.js';

/**
 * @param {{nets:{name:string,nodes:{ref:string,pin:string}[]}[], parts?:{ref:string,value?:string,footprint?:string}[]}} netlist
 * @param {{title?: string}} opts
 */
export function formatNetlist(netlist, { title = '' } = {}) {
  const lines = ['# Netlist generated by Circuits'];
  if (title) lines.push(`# ${title}`);
  const parts = (netlist.parts || []).slice().sort((a, b) => naturalCompare(a.ref, b.ref));
  lines.push('', `PARTS (${parts.length})`);
  const refW = Math.max(4, ...parts.map((p) => p.ref.length));
  const valW = Math.max(5, ...parts.map((p) => (p.value || '').length));
  for (const p of parts) lines.push(`  ${p.ref.padEnd(refW)}  ${(p.value || '').padEnd(valW)}  ${p.footprint || ''}`.trimEnd());
  const nets = (netlist.nets || []).slice().sort((a, b) => naturalCompare(a.name, b.name));
  lines.push('', `NETS (${nets.length})`);
  for (const n of nets) {
    const nodes = n.nodes.slice().sort((a, b) => naturalCompare(a.ref, b.ref) || naturalCompare(a.pin, b.pin));
    lines.push(`  ${n.name}: ${nodes.map((x) => `${x.ref}.${x.pin}`).join(' ')}`);
  }
  return lines.join('\n') + '\n';
}
