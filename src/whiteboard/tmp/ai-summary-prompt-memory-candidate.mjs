import assert from 'node:assert/strict';
import {board,item,validateBoard} from '../src/model.js';
import {boardText} from './ai-summary-prompt-memory-candidate.js';
const b=board('Summary memory fixture');
const f=item('frame',0,0,{text:'F'.repeat(20000),w:10000,h:10000});
b.items=[f,...Array.from({length:4999},(_,n)=>item('note',(n%100)*20,Math.floor(n/100)*20,{text:'Note '+n,parentId:f.id}))];
validateBoard(structuredClone(b));
assert.equal(b.items.length,5000);
assert.equal(typeof globalThis.gc,'function');
globalThis.gc();
const before=process.memoryUsage().heapUsed;
const start=performance.now();
globalThis.fixturePrompt=boardText(b.items);
const elapsed=performance.now()-start;
globalThis.gc();
const after=process.memoryUsage().heapUsed;
assert.equal(globalThis.fixturePrompt.length,50000);
assert.equal(globalThis.fixturePrompt.isWellFormed(),true);
console.log(JSON.stringify({validItems:b.items.length,sourceCharacters:b.items.reduce((n,i)=>n+i.text.length,0),resultCharacters:globalThis.fixturePrompt.length,elapsedMs:elapsed,retainedHeapIncrease:after-before,resultPrefix:globalThis.fixturePrompt.slice(0,12),resultTail:globalThis.fixturePrompt.slice(-12)}));
