import fs from 'node:fs';
import path from 'node:path';
import { validateBoard } from '../src/model.js';
const root='tmp/search-alternative-final-native';
const fixture=validateBoard(JSON.parse(fs.readFileSync('tmp/search-alternative-native-fixture.json','utf8')));
if(fixture.items.length!==3 || fixture.items.filter(i=>i.alt==='Résumé 😀').length!==2)throw Error('Invalid description fixture');
fs.mkdirSync(root,{recursive:true});
fs.cpSync('dist/assets',path.join(root,'assets'),{recursive:true});
fs.cpSync('dist/icons',path.join(root,'icons'),{recursive:true});
const dist=fs.readFileSync('dist/index.html','utf8');
const asset=dist.match(/src="([^" ]*\/assets\/index-[^" ]+\.js)"/)?.[1];
const css=dist.match(/href="([^" ]*\/assets\/index-[^" ]+\.css)"/)?.[1];
if(!asset||!css)throw Error('Missing production assets');
let html=fs.readFileSync('tmp/search-alternative-native/index-before.html','utf8');
html=html.replace(/await import\('[^']+'\)/,'await import('+JSON.stringify(asset)+')').replace(/href="\/assets\/index-[^"]+\.css"/,'href='+JSON.stringify(css));
html=html.replace("document.querySelector('#board-search-type')","document.querySelector('#board-search select')");
fs.writeFileSync(path.join(root,'index-final.html'),html);
const wrapper='<!doctype html><title>Alternative description search final</title><style>body{margin:0;overflow:hidden}iframe{width:1200px;height:800px;border:0}pre{position:fixed;left:1210px;top:0;width:650px;max-height:850px;overflow:auto;white-space:pre-wrap;font:14px monospace}</style><iframe src="index-final.html#local='+fixture.id+'"></iframe><pre></pre><script>addEventListener("message",e=>{if(e.source===document.querySelector("iframe").contentWindow&&e.data.results)document.querySelector("pre").textContent=JSON.stringify(e.data,null,2);})</script>';
fs.writeFileSync(path.join(root,'view-final.html'),wrapper);
fs.writeFileSync(path.join(root,'view-saved.html'),wrapper.replace('search final','saved search final'));
console.log({root,asset,css,id:fixture.id});
