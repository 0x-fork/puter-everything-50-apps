// Every query word must match an entry's names, keywords, or category in
// either language, ignoring accents and case.
export function searchIcons(query = "", category = "") {
  const words = fold(query).split(/\s+/).filter(Boolean);
  return searchable
    .filter(
      ({ entry, text }) =>
        (!category || entry.category === category) &&
        words.every((word) => text.includes(word)),
    )
    .map(({ entry }) => entry);
}
function canvasFor(size, createCanvas) {
  if (createCanvas) return createCanvas(size, size);
  const canvas = document.createElement("canvas");
  canvas.width = size;
  canvas.height = size;
  return canvas;
}
// Draws a pictogram or sticker into a square canvas at the given pixel size.
export function renderIcon(
  entry,
  { color = "#30342f", size = 192, createCanvas } = {},
) {
  const canvas = canvasFor(size, createCanvas),
    ctx = canvas.getContext("2d");
  ctx.clearRect(0, 0, size, size);
  if (entry.sticker) {
    ctx.fillStyle = entry.background;
    ctx.beginPath();
    ctx.arc(size / 2, size / 2, size / 2 - size / 48, 0, Math.PI * 2);
    ctx.fill();
    if (entry.node) {
      const glyph = size * 0.55;
      drawIconNode(ctx, entry.node, {
        x: (size - glyph) / 2,
        y: (size - glyph) / 2,
        size: glyph,
        color: entry.glyph,
        lineWidth: 2.25,
      });
    } else {
      ctx.fillStyle = entry.glyph;
      ctx.font = `600 ${size * 0.42}px "DM Sans", system-ui, sans-serif`;
      ctx.textAlign = "center";
      ctx.textBaseline = "middle";
      ctx.fillText(entry.label, size / 2, size / 2 + size * 0.02);
    }
  } else {
    // A one-unit margin keeps round stroke caps inside the image.
    const margin = size / 24,
      box = { x: margin, y: margin, size: size - margin * 2 };
    // Like stickers, icons carry their own contrast: a thin outline in the
    // light theme's board color, invisible there, keeps the dark icon
    // colors visible on the dark theme's board.
    drawIconNode(ctx, entry.node, { ...box, color: "#f7f9fc", lineWidth: 3 });
    drawIconNode(ctx, entry.node, { ...box, color, lineWidth: 2 });
  }
  return canvas;
}
export const iconDataURL = (entry, options) =>
  renderIcon(entry, options).toDataURL("image/png");
// A board image object for the pictogram, labelled with its localized name,
// which is also its alternative text for screen readers and exports.
export function iconItem(
  entry,
  x,
  y,
  { color, size = 96, lang = "en", createCanvas } = {},
) {
  return item("image", x, y, {
    w: size,
    h: size,
    src: iconDataURL(entry, {
      color,
      size: Math.min(512, Math.max(192, Math.ceil(size * 2))),
      createCanvas,
    }),
    text: entry.name[lang === "fr" ? 1 : 0],
    alt: entry.name[lang === "fr" ? 1 : 0],
    lang: lang === "fr" ? "fr" : "en",
  });
}
