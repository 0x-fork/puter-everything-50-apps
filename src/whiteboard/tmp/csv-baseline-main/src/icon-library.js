// White or ink, whichever stands out more from a sticker's badge, so the
// symbol on a light badge such as the gold star stays visible.
function glyphColor(background) {
  const n = parseInt(background.slice(1), 16);
  const [r, g, b] = [n >> 16, (n >> 8) & 255, n & 255].map((v) =>
    v / 255 <= 0.03928 ? v / 255 / 12.92 : ((v / 255 + 0.055) / 1.055) ** 2.4,
  );
  const light = 0.2126 * r + 0.7152 * g + 0.0722 * b;
  // Contrast with white is 1.05 / (light + 0.05); with the ink, #30342f,
  // it is (light + 0.05) / 0.0829.
  return 1.05 / (light + 0.05) >= (light + 0.05) / 0.0829
    ? "#ffffff"
    : "#30342f";
}
